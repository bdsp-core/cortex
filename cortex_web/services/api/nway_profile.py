"""Immutable production stamps for the owner-approved native IIIC profiles.

Which stamp a NEW precision sitting receives is decided by the fail-closed
response-model rollout (`response_model_rollout`): OFF (the default) stamps
the floor015 mixture profile; "email_allowlist"/"all" stamp the QUALIFIED
draw-latent profile per the promotion checklist's staged phases. Unknown
rollout values fail closed to the mixture — the previous behavior — exactly
as compute_rollout.py falls back to serial. Existing sittings always retain
their persisted stamp: both production stamps are permanently resumable, so
flipping the rollout (either direction) changes only new-session
assignment, never an in-progress sitting's response model.

Two retired stamps are deliberately NOT resumable and never stampable:

- `precision_nway_f1_ensemble9_fisher_v1` (unfloored, served
  2026-07-20..08-01) — the owner accepted restarting the in-progress
  sittings that carry it.
- `precision_nway_f1_engine_frame_atoms17_draw_latent_rd_v1` — the
  pre-qualification research escape (CORTEX_NWAY_RESEARCH_UNQUALIFIED),
  removed once the qualified draw-latent path landed; local testing now
  uses the real rollout (CORTEX_NWAY_RESPONSE_ROLLOUT=all).

Resume fails SOFT for an unlisted stamp — GET /api/session/active returns
{"active": null}, the SPA offers a fresh start, and the next new sitting
supersedes the stored one — so retired sittings end cleanly, never with an
opaque error.
"""
