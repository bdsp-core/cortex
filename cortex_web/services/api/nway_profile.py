def production_nway_profile(candidate_bank_sha256: str) -> dict:
    """Return the exact browser/server replay contract for a new sitting."""
    return {
        "engineProfileId": "precision_nway_f1_ensemble9_floor015_fisher_v1",
        "responseModel": RESPONSE_MODEL,
        "responseArtifactId": RESPONSE_ARTIFACT_ID,
        "responseArtifactSha256": RESPONSE_ARTIFACT_SHA256,
        "selectorVersion": SELECTOR_VERSION,
        "particleProfileVersion": PARTICLE_PROFILE_VERSION,
        "engineAlgorithmVersion": ENGINE_ALGORITHM_VERSION,
        "candidateBankSha256": candidate_bank_sha256,
    }


def qualified_draw_latent_nway_profile(candidate_bank_sha256: str) -> dict:
    """The qualified draw-latent stamp (nesting34, construction B)."""
    return {
        "engineProfileId": "precision_nway_f1_nesting34_draw_latent_v1",
        "responseModel": RESPONSE_MODEL,
        "responseArtifactId": QUALIFIED_DRAW_LATENT_ARTIFACT_ID,
        "responseArtifactSha256": QUALIFIED_DRAW_LATENT_ARTIFACT_SHA256,
        "selectorVersion": SELECTOR_VERSION,
        "particleProfileVersion": PARTICLE_PROFILE_VERSION,
        "engineAlgorithmVersion": ENGINE_ALGORITHM_VERSION,
        "candidateBankSha256": candidate_bank_sha256,
        "responseAggregation": "draw_latent",
    }


def response_model_rollout(db, cfg: dict, code: str) -> str:
    """Which response model a NEW sitting is stamped with. Fails closed.

    "all"             -> the qualified draw-latent profile
    "email_allowlist" -> qualified draw-latent only for normalized emails in
                         nway_response_emails; mixture for everyone else
    "off" / unknown   -> the floor015 mixture profile (previous behavior)
    """
    rollout = (cfg or {}).get("nway_response_rollout")
    if rollout == "all":
        return "qualified_draw_latent"
    if rollout != "email_allowlist":
        return "mixture"
    return ("qualified_draw_latent"
            if email_allowlisted(db, cfg, code, "nway_response_emails")
            else "mixture")


def nway_profile_for_new_session(candidate_bank_sha256: str, *,
                                 db=None, cfg=None, code=None) -> dict:
    """The stamp a NEW sitting receives. Fails closed to the mixture.

    Callers that cannot supply (db, cfg, code) — none in production — get
    the mixture, the fail-closed default.
    """
    if (cfg is not None and code is not None
            and response_model_rollout(db, cfg, code) == "qualified_draw_latent"):
        return qualified_draw_latent_nway_profile(candidate_bank_sha256)
    return production_nway_profile(candidate_bank_sha256)


def allowed_nway_profiles(candidate_bank_sha256: str) -> list[dict]:
    """Stamps a stored sitting may resume — always both PRODUCTION stamps.

    Resume is independent of the rollout state: per the promotion checklist,
    a rollback changes only new-session assignment and never an in-progress
    sitting's response model. The retired legacy unfloored stamp and the
    removed research escape stamp are deliberately absent (see module doc).
    """
    return [
        production_nway_profile(candidate_bank_sha256),
        qualified_draw_latent_nway_profile(candidate_bank_sha256),
    ]
